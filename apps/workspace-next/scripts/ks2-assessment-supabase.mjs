import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { test, cases, questions, fullAnswers, databaseAnswerKey } from './verify-ks2-assessment.mjs';
import { integrationSql } from './ks2-science-supabase.mjs';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const migrationPath = path.join(repo, 'supabase/migrations/20261024090000_register_ks2_science_assessment_test.sql');
const literal = value => `'${String(value).replaceAll("'", "''")}'`;
const json = value => `${literal(JSON.stringify(value))}::jsonb`;
const graderBody = fs.readFileSync(path.join(repo, 'supabase/schema.sql'), 'utf8').match(/create or replace function public\.math_part_scores\([\s\S]*?as \$\$([\s\S]*?)\$\$;/)[1];
const graderHash = createHash('md5').update(graderBody).digest('hex');
const rows = test.sections.flatMap(section => section.questions.map(q => ({ ...q, section: section.label })));

function registrationRows() {
  return `insert into public.tests (id,title,subject,level,status,total_points,app_path)
values (${literal(test.id)},${literal(test.title)},${literal(test.subject)},${literal(test.level)},'inactive',40,'/tests/${test.id}/start')
on conflict(id) do update set title=excluded.title,subject=excluded.subject,level=excluded.level,total_points=excluded.total_points,app_path=excluded.app_path;

insert into public.test_questions (id,test_id,part,prompt,answer_key,transcript_ref,points,position) values
${rows.map((q, i) => `(${[literal(q.id), literal(test.id), literal(q.section), literal(q.prompt), json(databaseAnswerKey(q)), 'null', q.points, i + 1].join(', ')})`).join(',\n')}
on conflict(id) do update set test_id=excluded.test_id,part=excluded.part,prompt=excluded.prompt,answer_key=excluded.answer_key,transcript_ref=excluded.transcript_ref,points=excluded.points,position=excluded.position;`;
}
function migrationSql() {
  return `-- Generated by: node apps/workspace-next/scripts/ks2-assessment-supabase.mjs --migration
-- Targeted registration only; reuse the previously verified numericRange grader.
-- Starts inactive and preserves an existing activation on rerun.
begin;
do $guard$
begin
  if md5((select prosrc from pg_proc where oid='public.math_part_scores(text,jsonb,jsonb)'::regprocedure)) <> '${graderHash}' then
    raise exception 'Expected the reviewed numericRange grader; inspect before registering Assessment Test';
  end if;
  if exists(select 1 from public.test_questions where id like 'ks2-sci-assessment-%' and test_id <> '${test.id}') then
    raise exception 'Assessment question identifiers belong to another test';
  end if;
end;
$guard$;

${registrationRows()}

do $counts$
begin
  if (select count(*) from public.test_questions where test_id='${test.id}') <> 34
    or (select sum(points) from public.test_questions where test_id='${test.id}') <> 40 then
    raise exception 'Assessment registration must contain exactly 34 parts and 40 marks';
  end if;
end;
$counts$;
commit;
`;
}
function auditSql() {
  const expectedRows = rows.map((q, i) => ({ id: q.id, prompt: q.prompt, part: q.section, position: i + 1, points: q.points, answer_key: databaseAnswerKey(q) }));
  const fixtures = cases.map(c => ({ id: c.id, answers: c.answer === undefined ? {} : { [c.id]: c.answer }, expected: c.expected, detail: c.detail }));
  return `-- Stateless checks of stored metadata and every browser scoring fixture.
do $audit$
declare fixture jsonb; expected_row jsonb; actual_key jsonb; actual numeric; total numeric;
begin
  if (select count(*) from public.test_questions where test_id='${test.id}') <> 34 then raise exception 'Expected 34 Assessment parts'; end if;
  for expected_row in select value from jsonb_array_elements(${json(expectedRows)}) loop
    if not exists(select 1 from public.test_questions q where q.id=expected_row->>'id' and q.test_id='${test.id}' and q.prompt=expected_row->>'prompt' and q.part=expected_row->>'part' and q.position=(expected_row->>'position')::integer and q.points=(expected_row->>'points')::numeric and q.answer_key=expected_row->'answer_key') then
      raise exception 'Assessment key or metadata differs for %', expected_row->>'id';
    end if;
  end loop;
  for fixture in select value from jsonb_array_elements(${json(fixtures)}) loop
    select answer_key into actual_key from public.test_questions where id=fixture->>'id';
    actual := public.answer_score(fixture->>'id',actual_key,public.answer_response(actual_key,fixture->'answers'),fixture->'answers');
    if actual is distinct from (fixture->>'expected')::numeric then
      raise exception 'Assessment scoring mismatch % (%): expected %, actual %',fixture->>'id',fixture->>'detail',fixture->>'expected',actual;
    end if;
  end loop;
  select sum(public.answer_score(id,answer_key,public.answer_response(answer_key,${json(fullAnswers)}),${json(fullAnswers)})) into total from public.test_questions where test_id='${test.id}';
  if total <> 40 then raise exception 'Assessment model answers scored %/40',total; end if;
  select sum(public.answer_score(id,answer_key,public.answer_response(answer_key,'{}'::jsonb),'{}'::jsonb)) into total from public.test_questions where test_id='${test.id}';
  if total <> 0 then raise exception 'Assessment blank answers scored %/40',total; end if;
end;
$audit$;
select jsonb_build_object('test_id','${test.id}','scoring_cases',${cases.length},'question_parts',34,'model_score',40,'possible',40,'blank_score',0) as assessment_scoring_verification;
`;
}
const mode = process.argv[2];
if (mode === '--migration') process.stdout.write(migrationSql());
else if (mode === '--bootstrap') process.stdout.write(`\n-- KS2 Science Assessment Test: generated keys, initially inactive.\n${registrationRows()}\n`);
else if (mode === '--audit') process.stdout.write(auditSql());
else if (mode === '--integration') process.stdout.write(integrationSql({ definition: test, answers: fullAnswers }));
else if (mode === '--answers') process.stdout.write(JSON.stringify(fullAnswers, null, 2) + '\n');
else if (mode === '--check') {
  assert.equal(fs.readFileSync(migrationPath, 'utf8'), migrationSql(), 'Regenerate the Assessment migration');
  assert.ok(fs.readFileSync(path.join(repo, 'supabase/schema.sql'), 'utf8').includes(registrationRows()), 'Regenerate Assessment bootstrap rows');
  assert.equal(questions.length, 34);
  console.log('Assessment Supabase migration and bootstrap match all 34 browser answer keys.');
} else throw new Error('Use --migration, --bootstrap, --audit, --integration, --answers or --check');
