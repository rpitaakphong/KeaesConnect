import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { test, cases, fullAnswers, databaseAnswerKey } from './verify-ks2-science.mjs';
import { diagnosticCases } from './verify-diagnostic-keys.mjs';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const migrationPath = path.join(repo, 'supabase/migrations/20261023090000_register_ks2_science_progress_test_1.sql');
const questions = test.sections.flatMap(section => section.questions.map(q => ({ ...q, section: section.label })));
const literal = value => `'${String(value).replaceAll("'", "''")}'`;
const json = value => `${literal(JSON.stringify(value))}::jsonb`;
const keyFor = q => databaseAnswerKey(q);
const definitions = [...fs.readFileSync(path.join(repo, 'supabase/schema.sql'), 'utf8').matchAll(/create or replace function public\.math_part_scores\([\s\S]*?\$\$;/g)];
assert.equal(definitions.length, 1);
const grader = definitions[0][0];
const graderBody = grader.match(/as \$\$([\s\S]*?)\$\$;/)[1];
const graderHash = createHash('md5').update(graderBody).digest('hex');

function registrationRows() {
  const rows = questions.map((q, index) => `(${[literal(q.id), literal(test.id), literal(q.section), literal(q.prompt), json(keyFor(q)), 'null', q.points, index + 1].join(', ')})`);
  return `insert into public.tests (id,title,subject,level,status,total_points,app_path)
values (${literal(test.id)},${literal(test.title)},${literal(test.subject)},${literal(test.level)},'inactive',40,'/tests/${test.id}/start')
on conflict(id) do update set title=excluded.title,subject=excluded.subject,level=excluded.level,total_points=excluded.total_points,app_path=excluded.app_path;

insert into public.test_questions (id,test_id,part,prompt,answer_key,transcript_ref,points,position) values
${rows.join(',\n')}
on conflict(id) do update set test_id=excluded.test_id,part=excluded.part,prompt=excluded.prompt,answer_key=excluded.answer_key,transcript_ref=excluded.transcript_ref,points=excluded.points,position=excluded.position;`;
}

function registrationSql() {
  return `-- Generated by: node apps/workspace-next/scripts/ks2-science-supabase.mjs --migration
-- Register inactive; activation follows verified scoring and rolled-back integration checks.
begin;
do $guard$
begin
  if md5((select prosrc from pg_proc where oid='public.math_part_scores(text,jsonb,jsonb)'::regprocedure))
    not in ('01773cdb4167b2dd10fd61b36221649b', '${graderHash}') then
    raise exception 'math_part_scores changed since review; inspect it before applying this migration';
  end if;
  if exists(select 1 from public.test_questions where id like 'ks2-sci-pt1-%' and test_id <> '${test.id}') then
    raise exception 'KS2 question identifiers belong to another test';
  end if;
end;
$guard$;

${grader}

${registrationRows()}

do $counts$
begin
  if (select count(*) from public.test_questions where test_id='${test.id}') <> 37
    or (select sum(points) from public.test_questions where test_id='${test.id}') <> 40 then
    raise exception 'KS2 registration must contain exactly 37 parts and 40 marks';
  end if;
end;
$counts$;
commit;
`;
}

function auditSql() {
  const fixtures = cases.map(row => {
    const id = `ks2-sci-pt1-${row.question}`;
    const expectedKey = keyFor(questions.find(q => q.id === id));
    return { id, answers: row.answer === undefined ? {} : { [id]: row.answer }, expected: row.expected, detail: row.detail,
      ...(JSON.stringify(row.key) === JSON.stringify(expectedKey) ? {} : { keyOverride: row.key }) };
  });
  for (const [suffix, answer, expected] of diagnosticCases) {
    const id = `cie-igcse-cs-p3-diagnostic-${suffix}`;
    fixtures.push({ id, answers: { [id]: answer }, expected, detail: 'existing diagnostic regression' });
  }
  const foodChain = { position1: 'killer whale', position2: 'dolphin', position3: 'fish', position4: 'crustacean', position5: 'phytoplankton' };
  for (const [answer, expected] of [[foodChain, 2], [{ ...foodChain, position2: 'wrong', position3: 'wrong', position4: 'wrong' }, 1], [{}, 0]]) {
    fixtures.push({ id: 'spip-y8s-q13', answers: { 'spip-y8s-q13': answer }, expected, detail: 'existing SPIP grouped marking' });
  }
  for (const [answer, expected] of [['\t23\n', 1], ['\u00a023\ufeff', 1], ['9'.repeat(400), 0], [23, 0], [null, 0], [{ answer: 23 }, 0], ['.23', 0], ['-23', 0]]) {
    fixtures.push({ id: 'ks2-sci-pt1-8c', answers: { 'ks2-sci-pt1-8c': answer }, expected, detail: 'strict finite decimal response' });
  }
  const expectedRows = questions.map((q, index) => ({ id: q.id, prompt: q.prompt, points: q.points, part: q.section, position: index + 1, answer_key: keyFor(q) }));
  return `-- Stateless marking checks: no student, assignment, or result rows are written.
do $audit$
declare fixture jsonb; expected_row jsonb; actual_key jsonb; actual numeric; total numeric;
begin
  if (select count(*) from public.test_questions where test_id='${test.id}') <> 37 then raise exception 'Expected 37 KS2 parts'; end if;
  for expected_row in select value from jsonb_array_elements(${json(expectedRows)}) loop
    if not exists(select 1 from public.test_questions q where q.id=expected_row->>'id' and q.test_id='${test.id}' and q.prompt=expected_row->>'prompt' and q.part=expected_row->>'part' and q.position=(expected_row->>'position')::integer and q.points=(expected_row->>'points')::numeric and q.answer_key=expected_row->'answer_key') then
      raise exception 'Database key or metadata differs for %', expected_row->>'id';
    end if;
  end loop;
  for fixture in select value from jsonb_array_elements(${json(fixtures)}) loop
    select answer_key into actual_key from public.test_questions where id=fixture->>'id';
    if actual_key is null then raise exception 'Missing regression key %',fixture->>'id'; end if;
    actual_key := coalesce(fixture->'keyOverride',actual_key);
    actual := public.answer_score(fixture->>'id',actual_key,public.answer_response(actual_key,fixture->'answers'),fixture->'answers');
    if actual is distinct from (fixture->>'expected')::numeric then
      raise exception 'Scoring mismatch for % (%): expected %, actual %',fixture->>'id',fixture->>'detail',fixture->>'expected',actual;
    end if;
  end loop;
  select sum(public.answer_score(id,answer_key,public.answer_response(answer_key,${json(fullAnswers)}),${json(fullAnswers)})) into total from public.test_questions where test_id='${test.id}';
  if total <> 40 then raise exception 'Model answers scored %/40',total; end if;
  select sum(public.answer_score(id,answer_key,public.answer_response(answer_key,'{}'::jsonb),'{}'::jsonb)) into total from public.test_questions where test_id='${test.id}';
  if total <> 0 then raise exception 'Blank answers scored %/40',total; end if;
end;
$audit$;
select jsonb_build_object('ks2_cases',318,'diagnostic_cases',${diagnosticCases.length},'spip_cases',3,'extra_numeric_cases',8,'model_score',40,'possible',40,'blank_score',0,'question_parts',37) as scoring_verification;
`;
}

export function integrationSql({ definition = test, answers = fullAnswers } = {}) {
  const partCount = definition.sections.reduce((n, section) => n + section.questions.length, 0);
  return `-- Every synthetic write is rolled back inside an exception subtransaction.
create or replace function pg_temp.ks2_setup_integration() returns jsonb language plpgsql as $integration$
declare
  staff_id uuid; assignment record; report record; result jsonb; branch_name text;
  summaries jsonb := '[]'::jsonb; before_counts jsonb; after_counts jsonb;
begin
  before_counts := jsonb_build_array((select count(*) from public.students),(select count(*) from public.test_assignments),(select count(*) from public.test_attempts),(select count(*) from public.attempt_answers));
  select id into staff_id from public.staff_users where role='super_admin' and deleted_at is null order by created_at limit 1;
  if staff_id is null then raise exception 'An existing super admin is required for assignment/report checks'; end if;
  begin
    perform set_config('request.jwt.claim.sub',staff_id::text,true);
    update public.tests set status='active' where id='${definition.id}';
    foreach branch_name in array array['ram','ekamai'] loop
      select * into assignment from public.create_test_assignment('${definition.id}',branch_name);
      if not exists(select 1 from public.get_assignment(assignment.assignment_token) where test_id='${definition.id}' and branch=branch_name) then raise exception 'Assignment lookup failed'; end if;
      result := public.submit_attempt(assignment.assignment_token,jsonb_build_object('fullName','KS2 Setup QA - rolled back','nickname','QA','dateOfBirth','2000-01-01','testDate',current_date),${json(answers)});
      if (result->>'total')::numeric <> 40 or (result->>'possible')::numeric <> 40 then raise exception 'Submission did not score 40/40: %',result; end if;
      if (select count(*) from public.attempt_answers where attempt_id=(result->>'attemptId')::uuid) <> ${partCount} then raise exception 'Submission did not store ${partCount} answers'; end if;
      select * into report from public.get_admin_result((result->>'attemptId')::uuid);
      if report.attempt_id is null or report.branch <> branch_name or report.score_total <> 40 or report.score_possible <> 40 then raise exception 'Admin report verification failed'; end if;
      if exists(select 1 from public.get_assignment(assignment.assignment_token)) then raise exception 'Submitted assignment remains available'; end if;
      begin
        perform public.submit_attempt(assignment.assignment_token,jsonb_build_object('fullName','KS2 duplicate QA','nickname','QA','dateOfBirth','2000-01-01'),${json(answers)});
        raise exception 'Duplicate submission was accepted';
      exception when others then
        if position('already been used' in sqlerrm)=0 then raise; end if;
      end;
      summaries := summaries || jsonb_build_array(jsonb_build_object('branch',branch_name,'score',40,'possible',40,'answers',${partCount},'single_use',true,'admin_report',true));
    end loop;
    raise exception using errcode='ZK001',message='Roll back synthetic KS2 integration rows';
  exception when sqlstate 'ZK001' then null;
  end;
  after_counts := jsonb_build_array((select count(*) from public.students),(select count(*) from public.test_assignments),(select count(*) from public.test_attempts),(select count(*) from public.attempt_answers));
  if before_counts <> after_counts then raise exception 'Integration test left persistent data'; end if;
  return jsonb_build_object('branches',summaries,'rolled_back',true,'history_counts_unchanged',true);
end;
$integration$;
select pg_temp.ks2_setup_integration() as integration_verification;
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (mode === '--migration') process.stdout.write(registrationSql());
  else if (mode === '--bootstrap') process.stdout.write(`\n-- KS2 Science: generated from the reviewed definition; activate after verification.\n${registrationRows()}\n`);
  else if (mode === '--audit') process.stdout.write(auditSql());
  else if (mode === '--integration') process.stdout.write(integrationSql());
  else if (mode === '--answers') process.stdout.write(JSON.stringify(fullAnswers, null, 2) + '\n');
  else if (mode === '--check') {
    assert.equal(fs.readFileSync(migrationPath, 'utf8'), registrationSql(), 'Regenerate the KS2 migration from the current definition');
    assert.ok(fs.readFileSync(path.join(repo, 'supabase/schema.sql'), 'utf8').includes(registrationRows()), 'Regenerate the KS2 bootstrap rows');
    console.log('KS2 Supabase migration matches all 37 reviewed question keys and the opt-in numeric grader.');
  } else throw new Error('Use --migration, --bootstrap, --audit, --integration, --answers or --check');
}
